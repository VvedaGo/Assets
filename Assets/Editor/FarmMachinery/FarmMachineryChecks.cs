    /// <summary>
    /// Import checks of the Farm Machinery prefabs against CATALOG.md and the real numbers for the release card, written to
    /// .work/ImportCheck_FarmMachinery.md (outside Assets, like the PackPrefabBuilder report).
    /// </summary>
    public static class FarmMachineryChecks
    {
        public const string ReportPath = ".work/ImportCheck_FarmMachinery.md";

        // Attachments that hang on a linkage / feeder by design (specs ATT-01..05: "not meant to stand on the ground").
        private static readonly HashSet<string> Hanging = new HashSet<string> { "ATT-01", "ATT-02", "ATT-03", "ATT-04", "ATT-05" };

        /// <summary>Runs with the Full items staged into the Lite working root (see FarmMachineryRelease.Staged).</summary>
        [MenuItem("Tools/Farm Machinery/Check Prefabs")]
        public static string Run() => FarmMachineryRelease.Staged(RunStaged);

        private static string RunStaged()
        {
            var md = new StringBuilder();
            var issues = new List<string>();
            md.AppendLine("# FarmMachinery — import check (Э10 import)\n");
            md.AppendLine($"Generated by `FarmMachineryChecks.Run()` ({System.DateTime.Now:yyyy-MM-dd HH:mm}). Unity {Application.unityVersion}, URP. Source rows: CATALOG.md v0.1.\n");

            // ---- per base prefab
            md.AppendLine("## Base prefabs (26)\n");
            md.AppendLine("| ID | Prefab | LOD0 tris | Budget | LOD1 tris | LOD1 % | LODGroup | Catalogue LOD | BoxCollider | Size X×Y×Z, m | min Y | Points | Parts | Issues |");
            md.AppendLine("|---|---|---:|---:|---:|---:|---|---|---|---|---:|---|---|---|");
            var rows = new List<(FarmMachineryItem Item, int Lod0, int Lod1)>();
            foreach (var item in Items)
            {
                var path = BasePath(item.Id);
                var go = AssetDatabase.LoadAssetAtPath<GameObject>(path);
                if (go == null) { issues.Add($"{item.Id}: base prefab missing ({path})"); md.AppendLine($"| {item.Id} | MISSING | | | | | | | | | | | | |"); continue; }
                var all = go.GetComponentsInChildren<MeshRenderer>(true);
                var lod0 = all.Where(r => !r.name.EndsWith("_Low1")).ToArray();
                var lod1 = all.Where(r => r.name.EndsWith("_Low1")).ToArray();
                int t0 = Tris(lod0), t1 = Tris(lod1);
                rows.Add((item, t0, t1));
                var own = new List<string>();
                own.AddRange(CommonChecks(go));
                var group = go.GetComponent<LODGroup>();
                if (item.Lod != (group != null)) own.Add(item.Lod ? "LODGroup missing" : "unexpected LODGroup");
                if (group != null && group.lodCount != 2) own.Add($"LODGroup has {group.lodCount} levels");
                foreach (var r in lod1)
                {
                    var part = r.name.Substring(0, r.name.Length - 5);
                    if (r.transform.parent == null || r.transform.parent.name != part) own.Add($"{r.name} not under {part}");
                }
                var missingPoints = item.Points.Where(p => { var t = Find(go, p); return t == null || t.GetComponent<Renderer>() != null; }).ToList();
                var missingParts = item.Parts.Where(p => Find(go, p) == null).ToList();
                if (missingPoints.Count > 0) own.Add("points missing/not empty: " + string.Join(",", missingPoints));
                if (missingParts.Count > 0) own.Add("parts missing: " + string.Join(",", missingParts));
                var b = BoundsAll(go);
                var minYNote = Mathf.Abs(b.min.y) > 0.005f ? (Hanging.Contains(item.Id) ? " (hangs by spec)" : "") : "";
                if (Mathf.Abs(b.min.y) > 0.005f && !Hanging.Contains(item.Id)) own.Add($"min Y {b.min.y:F3}");
                if (t0 > item.Budget) own.Add($"over budget {t0}/{item.Budget}");
                issues.AddRange(own.Select(o => $"{item.Id}: {o}"));
                md.AppendLine($"| {item.Id} | {go.name} | {t0} | {item.Budget} | {(t1 > 0 ? t1.ToString() : "—")} | {(t1 > 0 ? $"{100f * t1 / t0:F0}" : "—")} | " +
                              $"{(group != null ? "yes" : "no")} | {(item.Lod ? "yes" : "no")} | {(go.GetComponent<BoxCollider>() != null ? "yes" : "NO")} | " +
                              $"{b.size.x:F2}×{b.size.y:F2}×{b.size.z:F2} | {b.min.y:F3}{minYNote} | {(item.Points.Length - missingPoints.Count)}/{item.Points.Length} | " +
                              $"{(item.Parts.Length - missingParts.Count)}/{item.Parts.Length} | {(own.Count == 0 ? "—" : string.Join("; ", own))} |");
            }

            // ---- variants and compositions
            md.AppendLine("\n## Variants (15)\n");
            md.AppendLine("| ID | Prefab | Prefab Variant of | Material | Size X×Y×Z, m | min Y | Issues |");
            md.AppendLine("|---|---|---|---|---|---:|---|");
            foreach (var (id, variant) in Variants)
            {
                var path = PrefabPath(id, variant);
                var go = AssetDatabase.LoadAssetAtPath<GameObject>(path);
                if (go == null) { issues.Add($"{id} {variant}: variant missing ({path})"); md.AppendLine($"| {id} | MISSING {Path.GetFileName(path)} | | | | | |"); continue; }
                var own = CommonChecks(go).ToList();
                var source = PrefabUtility.GetCorrespondingObjectFromSource(go);
                var isVariant = PrefabUtility.GetPrefabAssetType(go) == PrefabAssetType.Variant;
                if (!isVariant || source == null || AssetDatabase.GetAssetPath(source) != BasePath(id)) own.Add("not a Prefab Variant of the base");
                var b = BoundsAll(go);
                if (Mathf.Abs(b.min.y) > 0.005f) own.Add($"min Y {b.min.y:F3}");
                var load = Find(go, "Load_Grain");
                if (load != null && load.gameObject.activeSelf != (variant == "Grain" || variant == "Full")) own.Add("Load_Grain state wrong");
                var mats = string.Join(",", go.GetComponentsInChildren<Renderer>(true).SelectMany(r => r.sharedMaterials).Where(m => m != null).Select(m => m.name).Distinct());
                issues.AddRange(own.Select(o => $"{id} {variant}: {o}"));
                md.AppendLine($"| {id} {variant} | {go.name} | {(source != null ? source.name : "—")} | {mats} | {b.size.x:F2}×{b.size.y:F2}×{b.size.z:F2} | {b.min.y:F3} | {(own.Count == 0 ? "—" : string.Join("; ", own))} |");
            }
            foreach (var (id, variant) in new[] { ("TRL-01", (string)null), ("TRL-05", null) })
            {
                var load = Find(LoadPrefab(id), "Load_Grain");
                if (load == null || load.gameObject.activeSelf) issues.Add($"{id} base: Load_Grain should be inactive (Empty)");
            }

            md.AppendLine("\n## Compositions\n");
            var compDir = $"{FarmMachineryPackBuilder.Config.PrefabDir}/CMP";
            var comps = AssetDatabase.FindAssets("t:Prefab", new[] { compDir }).Select(AssetDatabase.GUIDToAssetPath).OrderBy(p => p).ToList();
            foreach (var path in comps)
            {
                var go = AssetDatabase.LoadAssetAtPath<GameObject>(path);
                var nested = go.transform.Cast<Transform>().Select(t => PrefabUtility.GetCorrespondingObjectFromSource(t.gameObject)).ToList();
                var foreign = nested.Where(n => n == null || !AssetDatabase.GetAssetPath(n).StartsWith(FarmMachineryPackBuilder.Config.PrefabDir)).Count();
                var b = BoundsAll(go);
                if (foreign > 0) issues.Add($"{go.name}: {foreign} children are not pack prefabs");
                md.AppendLine($"- `{go.name}`: {nested.Count} nested pack prefabs ({string.Join(", ", nested.Where(n => n != null).GroupBy(n => n.name).Select(g => g.Count() > 1 ? $"{g.Key} ×{g.Count()}" : g.Key))}); " +
                              $"size {b.size.x:F1}×{b.size.y:F1}×{b.size.z:F1} m, min Y {b.min.y:F3}, root scale {go.transform.localScale.x:F0}, rotation {go.transform.localEulerAngles.magnitude:F0}");
            }
            if (comps.Count != 5) issues.Add($"{comps.Count} composition prefabs (5 expected)");

            // ---- LOD1 follows the moving part
            md.AppendLine("\n## LOD1 follows its part (test instance)\n");
            md.AppendLine(LodFollowTest(issues));

            // ---- totals
            md.AppendLine("\n## Totals (release numbers)\n");
            void Totals(string label, IEnumerable<(FarmMachineryItem Item, int Lod0, int Lod1)> set)
            {
                var s = set.ToList();
                var min = s.OrderBy(r => r.Lod0).First(); var max = s.OrderBy(r => r.Lod0).Last();
                var withLod = s.Where(r => r.Lod1 > 0).ToList();
                md.AppendLine($"- **{label}** ({s.Count} models): LOD0 tris min {min.Lod0} ({min.Item.Id} {min.Item.Name}), max {max.Lod0} ({max.Item.Id} {max.Item.Name}), " +
                              $"total {s.Sum(r => r.Lod0)} (budget sum {s.Sum(r => r.Item.Budget)}); LOD1 on {withLod.Count} models, LOD1 tris min {withLod.Min(r => r.Lod1)}, " +
                              $"max {withLod.Max(r => r.Lod1)}, total {withLod.Sum(r => r.Lod1)} ({100f * withLod.Sum(r => r.Lod1) / withLod.Sum(r => r.Lod0):F0} % of their LOD0).");
            }
            Totals("Full", rows);
            Totals("Lite", rows.Where(r => r.Item.Lite));
            var matPaths = AssetDatabase.FindAssets("t:Material", new[] { FarmMachineryPackBuilder.Config.MaterialDir }).Select(AssetDatabase.GUIDToAssetPath).ToList();
            var texPaths = AssetDatabase.FindAssets("t:Texture2D", new[] { FarmMachineryPackBuilder.Config.TextureDir }).Select(AssetDatabase.GUIDToAssetPath).ToList();
            md.AppendLine($"- Materials: {matPaths.Count} ({string.Join(", ", matPaths.Select(Path.GetFileNameWithoutExtension))}), shader " +
                          string.Join("/", matPaths.Select(p => AssetDatabase.LoadAssetAtPath<Material>(p).shader.name).Distinct()) + "; one material per prefab.");
            md.AppendLine($"- Textures: {texPaths.Count} — " + string.Join(", ", texPaths.Select(p =>
            {
                var t = AssetDatabase.LoadAssetAtPath<Texture2D>(p); var imp = (TextureImporter)AssetImporter.GetAtPath(p);
                return $"{t.name} {t.width}×{t.height} {imp.filterMode}, mipmaps {(imp.mipmapEnabled ? "on" : "off")}, {imp.textureCompression}, sRGB {imp.sRGBTexture}";
            })));
            var basePrefabs = rows.Count; var variants = Variants.Count(v => AssetDatabase.LoadAssetAtPath<GameObject>(PrefabPath(v.Id, v.Variant)) != null);
            md.AppendLine($"- Prefabs: {basePrefabs} base + {variants} variants = {basePrefabs + variants} (CATALOG «Итоги»: 41); compositions {comps.Count} (CATALOG: 5).");
            var envPrefabs = AssetDatabase.IsValidFolder($"{FarmMachineryEnvironment.Root}/Prefabs")
                ? AssetDatabase.FindAssets("t:Prefab", new[] { $"{FarmMachineryEnvironment.Root}/Prefabs" }).Length : 0;
            md.AppendLine($"- Environment (DEM-01…05, demo only, not counted above): {envPrefabs} prefabs in {FarmMachineryEnvironment.Root}, " +
                          $"own atlas and material M_FarmMachinery_Demo; numbers in {FarmMachineryEnvironment.ReportPath}.");

            md.AppendLine("\n## Issues\n");
            md.AppendLine(issues.Count == 0 ? "None." : string.Join("\n", issues.Select(i => "- " + i)));
            File.WriteAllText(ReportPath, md.ToString());
            var summary = $"[FarmMachinery] check: {basePrefabs} base, {variants} variants, {comps.Count} compositions, {issues.Count} issues -> {ReportPath}\n" + string.Join("\n", issues);
            Debug.Log(summary);
            return summary;
        }

        /// <summary>Root transform, materials (no pink), collider.</summary>
        private static IEnumerable<string> CommonChecks(GameObject go)
        {
            if (go.transform.localScale != Vector3.one) yield return $"root scale {go.transform.localScale}";
            if (go.transform.localRotation != Quaternion.identity) yield return $"root rotation {go.transform.localEulerAngles}";
            if (go.GetComponent<BoxCollider>() == null) yield return "no BoxCollider";
            foreach (var r in go.GetComponentsInChildren<Renderer>(true))
                foreach (var m in r.sharedMaterials)
                {
                    if (m == null) { yield return $"{r.name}: null material (pink)"; continue; }
                    if (m.shader == null || !m.shader.isSupported || m.shader.name != "Universal Render Pipeline/Lit") yield return $"{r.name}: shader {m.shader?.name} (pink risk)";
                    if (m.GetTexture("_BaseMap") == null) yield return $"{r.name}: {m.name} without _BaseMap";
                }
        }

        /// <summary>Active LOD0 renderers of a prefab asset (base of TRL-01/05: Load_Grain is off and lies inside the body anyway).</summary>
        private static Bounds BoundsAll(GameObject go) => Lod0Bounds(go.GetComponentsInChildren<MeshRenderer>(true));

        /// <summary>Rotates Wheel_FL of TRC-01 by 90° about X in a test instance and checks that Wheel_FL_Low1 turns with it.</summary>
        private static string LodFollowTest(List<string> issues)
        {
            return InPreviewScene(scene =>
            {
                var sb = new StringBuilder();
                foreach (var (id, part) in new[] { ("TRC-01", "Wheel_FL"), ("HRV-01", "Auger_Unload"), ("TRL-01", "Bed"), ("IMP-07", "Arm_L") })
                {
                    var go = Instantiate(LoadPrefab(id), scene);
                    var p = Require(go, part);
                    var low = Require(go, part + "_Low1");
                    var lowRelBefore = Quaternion.Inverse(p.rotation) * low.rotation;
                    var lowRotBefore = low.rotation; var lowPosRelBefore = p.InverseTransformPoint(Lod0BoundsCenter(low));
                    var axis = part == "Wheel_FL" ? Vector3.right : part == "Auger_Unload" ? Vector3.up : part == "Bed" ? Vector3.right : Vector3.forward;
                    p.localRotation = Quaternion.AngleAxis(90, axis) * p.localRotation;
                    var turned = Quaternion.Angle(lowRotBefore, low.rotation);
                    var rel = Quaternion.Angle(lowRelBefore, Quaternion.Inverse(p.rotation) * low.rotation);
                    var drift = Vector3.Distance(lowPosRelBefore, p.InverseTransformPoint(Lod0BoundsCenter(low)));
                    var ok = low.parent == p && Mathf.Abs(turned - 90) < 0.5f && rel < 0.01f && drift < 0.001f;
                    sb.AppendLine($"- {id}: `{part}` rotated 90° about {(axis == Vector3.right ? "X" : axis == Vector3.up ? "Y" : "Z")} → `{low.name}` parent `{low.parent.name}`, " +
                                  $"turned {turned:F1}°, offset to the part {rel:F3}° / {drift * 1000:F1} mm → {(ok ? "follows" : "DOES NOT follow")}");
                    if (!ok) issues.Add($"{id}: {low.name} does not follow {part}");
                    Object.DestroyImmediate(go);
                }
                return sb.ToString();
            });
        }

        private static Vector3 Lod0BoundsCenter(Transform t)
        {
            var mb = t.GetComponent<MeshFilter>().sharedMesh.bounds;
            return t.TransformPoint(mb.center);
        }
    }
